import Foundation

public enum ADCEdidProfiles {
    public static func studioDisplayOEMProfile(for recommendation: ADCOEMResolution) -> Data? {
        switch (recommendation.width, recommendation.height) {
        case (800, 600), (832, 624), (1024, 768), (1056, 792), (1280, 1024), (1600, 1200):
            return studioDisplayAllOEM
        default:
            return nil
        }
    }

    public static let studioDisplayAllOEM: Data = {
        var base = edidBytes(primary: timing1600, secondary: timing1280)
        base[126] = 1
        base[127] = checksum(for: base.prefix(127))

        var extensionBlock = [UInt8](repeating: 0, count: 128)
        extensionBlock[0] = 0x02
        extensionBlock[1] = 0x03
        extensionBlock[2] = 0x04
        extensionBlock[3] = 0x00
        for (index, timing) in [timing1056, timing1024, timing832, timing800, timing640].enumerated() {
            let start = 4 + index * 18
            extensionBlock.replaceSubrange(start..<start + 18, with: timing)
        }
        extensionBlock[127] = checksum(for: extensionBlock.prefix(127))
        return Data(base + extensionBlock)
    }()

    private static func edid(primary: [UInt8], secondary: [UInt8] = timing1600) -> Data {
        Data(edidBytes(primary: primary, secondary: secondary))
    }

    private static func edidBytes(primary: [UInt8], secondary: [UInt8] = timing1600) -> [UInt8] {
        var bytes = baseEDID
        bytes.replaceSubrange(54..<72, with: primary)
        bytes.replaceSubrange(72..<90, with: secondary)
        bytes[126] = 0
        bytes[127] = checksum(for: bytes.prefix(127))
        return bytes
    }

    private static func checksum<S: Sequence>(for bytes: S) -> UInt8 where S.Element == UInt8 {
        let sum = bytes.reduce(0) { ($0 + Int($1)) & 0xff }
        return UInt8((256 - sum) & 0xff)
    }

